-- Mevcut bakiye anlık görüntülerini tarih sırasına göre yeniden hesapla.
UPDATE "balances" b SET "amount" = s.running
FROM (
  SELECT id, (SUM(CASE WHEN type = 'income' THEN amount ELSE -amount END)
              OVER (PARTITION BY account_id ORDER BY occurred_at, id))::bigint AS running
  FROM "transactions"
) s
WHERE b.transaction_id = s.id AND b.amount <> s.running;

