-- Grup işlemlerinde her üyenin payı. Bir işlemin payları toplamı işlem tutarına eşittir.
CREATE TABLE "transaction_splits" (
  "transaction_id" integer NOT NULL REFERENCES "transactions" ("id") ON DELETE CASCADE,
  "user_id" integer NOT NULL REFERENCES "users" ("id"),
  "amount" bigint NOT NULL CHECK ("amount" >= 0),
  PRIMARY KEY ("transaction_id", "user_id")
);
CREATE INDEX ON "transaction_splits" ("user_id");

-- Mevcut grup işlemleri için güncel üyeler arasında eşit pay (kalan kuruşlar küçük id'li üyelere).
INSERT INTO "transaction_splits" ("transaction_id", "user_id", "amount")
SELECT t.id, m.user_id,
       t.amount / m.cnt + CASE WHEN m.rn <= t.amount % m.cnt THEN 1 ELSE 0 END
FROM "transactions" t
JOIN (
  SELECT group_id, user_id,
         row_number() OVER (PARTITION BY group_id ORDER BY user_id) AS rn,
         count(*) OVER (PARTITION BY group_id) AS cnt
  FROM "group_members"
) m ON m.group_id = t.group_id
WHERE t.group_id IS NOT NULL;

-- Grup içi borç ödemeleri.
CREATE TABLE "settlements" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "group_id" integer NOT NULL REFERENCES "groups" ("id"),
  "from_user_id" integer NOT NULL REFERENCES "users" ("id"),
  "to_user_id" integer NOT NULL REFERENCES "users" ("id"),
  "amount" bigint NOT NULL CHECK ("amount" > 0),
  "currency" varchar(3) NOT NULL,
  "transaction_id" integer UNIQUE REFERENCES "transactions" ("id"),
  "note" varchar,
  "created_by" integer NOT NULL REFERENCES "users" ("id"),
  "occurred_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CHECK ("from_user_id" <> "to_user_id")
);
CREATE INDEX ON "settlements" ("group_id");
COMMENT ON COLUMN "settlements"."transaction_id" IS 'kaydı ekleyenin hesabına yansıyan işlem (opsiyonel)';

-- Tekrarlayan işlemler (kira, aidat, fatura...).
CREATE TYPE "recurrence_frequency" AS ENUM ('weekly', 'monthly', 'yearly');

CREATE TABLE "recurring_transactions" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "account_id" integer NOT NULL REFERENCES "accounts" ("id"),
  "group_id" integer REFERENCES "groups" ("id"),
  "type" transaction_type NOT NULL,
  "amount" bigint NOT NULL CHECK ("amount" > 0),
  "description" varchar,
  "split" jsonb,
  "frequency" recurrence_frequency NOT NULL,
  "interval_count" integer NOT NULL DEFAULT 1 CHECK ("interval_count" BETWEEN 1 AND 12),
  "anchor_day" integer NOT NULL CHECK ("anchor_day" BETWEEN 1 AND 31),
  "next_run_on" date NOT NULL,
  "end_on" date,
  "active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);
CREATE INDEX ON "recurring_transactions" ("account_id");
CREATE INDEX ON "recurring_transactions" ("group_id");
CREATE INDEX ON "recurring_transactions" ("next_run_on") WHERE "active";
COMMENT ON COLUMN "recurring_transactions"."anchor_day" IS 'ayın kaçında; kısa aylarda ay sonuna çekilir';

